// App shell: routing, data status, refresh, theme, affiliations.
import * as api from "./api.js";
import { disposeAll } from "./charts.js";
import { errorBox, fmt, h, loading, onThemeChange, toast } from "./ui.js";
import { renderOverview } from "./views/overview.js";
import { renderFlights, renderFlightDetail, renderCompare } from "./views/flights.js";
import { renderMap } from "./views/map.js";
import { renderAircraftIndex, renderAircraft } from "./views/aircraft.js";
import { renderDataset } from "./views/dataset.js";
import { renderAbout } from "./views/about.js";

const app = document.getElementById("app");
export const state = { status: null, refreshing: false, autoTimer: null, site: null };

const routes = [
  [/^#?\/?$/, () => renderOverview(app)],
  [/^#\/flights\/compare\/([\d,]+)$/, (m) => renderCompare(app, m[1].split(",").map(Number))],
  [/^#\/flights\/(\d+)$/, (m) => renderFlightDetail(app, Number(m[1]))],
  [/^#\/flights(\?.*)?$/, (m) => renderFlights(app, new URLSearchParams((m[1] || "").slice(1)))],
  [/^#\/map(\?.*)?$/, (m) => renderMap(app, new URLSearchParams((m[1] || "").slice(1)))],
  [/^#\/aircraft\/([\w-]+)$/, (m) => renderAircraft(app, decodeURIComponent(m[1]))],
  [/^#\/aircraft$/, () => renderAircraftIndex(app)],
  [/^#\/dataset(\/[\w-]+)?$/, (m) => renderDataset(app, m[1] ? m[1].slice(1) : null)],
  [/^#\/about$/, () => renderAbout(app)],
];

let routeToken = 0;
export async function route() {
  const token = ++routeToken;
  disposeAll();
  const hash = location.hash || "#/";
  document.querySelectorAll(".nav a").forEach((a) => {
    const base = a.getAttribute("href");
    const on = base === "#/" ? hash === "#/" || hash === "" : hash.startsWith(base);
    if (on) a.setAttribute("aria-current", "page"); else a.removeAttribute("aria-current");
  });
  app.innerHTML = "";
  app.append(loading());
  for (const [re, fn] of routes) {
    const m = hash.match(re);
    if (m) {
      try {
        await fn(m);
      } catch (e) {
        if (token !== routeToken) return;
        console.error(e);
        app.innerHTML = "";
        app.append(h("div", { class: "wrap section" }, errorBox(e, () => route())));
      }
      if (token === routeToken && !hash.includes("?")) app.focus({ preventScroll: true });
      return;
    }
  }
  app.innerHTML = "";
  app.append(h("div", { class: "wrap section" }, h("h1", {}, "Page not found"), h("p", {}, h("a", { href: "#/" }, "Go to the overview"))));
}

// ---------------------------------------------------------------- status & refresh
const dot = document.getElementById("status-dot");
const text = document.getElementById("status-text");
const btn = document.getElementById("refresh-btn");
const detail = document.getElementById("refresh-detail");

function showStatus(st, busy = false, err = null) {
  dot.className = "dot " + (err ? "err" : busy ? "busy" : "ok");
  if (err) { text.textContent = "Refresh failed"; return; }
  if (busy) { text.textContent = "Refreshing…"; return; }
  if (!st) return;
  const ds = st.dataset || {};
  const when = st.mode === "static" ? st.published_at : (st.refresh && st.refresh.at) || st.loaded_at;
  text.textContent = `${st.mode === "static" ? "Snapshot" : "Refreshed"} ${fmt.ago(when)} · latest session ${fmt.date(ds.last_session_utc)}`;
  text.title = `Dataset exported ${fmt.dateTime(ds.created_utc)}; ${fmt.int(ds.n_sessions)} sessions; last refresh ${fmt.dateTime(when)}`;
  const portal = st.portal;
  detail.textContent = st.mode === "static"
    ? "Static snapshot: refresh re-fetches the published files."
    : portal && portal.checked_at ? `Portal checked ${fmt.ago(portal.checked_at)}: ${portal.message}`
    : st.portal_check_available ? "Refresh also lists new sessions on the Pipistrel portal (server side)."
    : "Portal check unavailable: credentials are not configured on this server. Refresh re-reads the processed dataset.";
  document.getElementById("footer-version").textContent =
    `Dataset export ${fmt.dateTime(ds.created_utc)}${ds.pipeline_commit ? `, pipeline ${ds.pipeline_commit}` : ""}; sessions ${fmt.date(ds.first_session_utc)} – ${fmt.date(ds.last_session_utc)}.`;
  banners(st);
}

function banners(st) {
  const slot = document.getElementById("banner-slot");
  slot.innerHTML = "";
  if (st && st.dataset && st.dataset.synthetic) {
    slot.append(h("div", { class: "banner synthetic", role: "note" }, h("b", {}, "Synthetic demonstration data."),
      " Every number and track on this site is generated by the pipeline's test generator, not recorded flights. Load a real export with `eplanes export-web`."));
  }
}

async function pollPortal() {
  for (let i = 0; i < 90; i++) {
    await new Promise((r) => setTimeout(r, 2000));
    const st = await api.status();
    state.status = st;
    if (!st.portal || st.portal.status !== "running") return st;
    text.textContent = "Checking the Pipistrel portal…";
  }
  return state.status;
}

export async function refresh({ quiet = false } = {}) {
  if (state.refreshing) return;
  state.refreshing = true;
  btn.disabled = true;
  btn.querySelector("svg").classList.add("spin");
  showStatus(null, true);
  try {
    const usePortal = !!(state.status && state.status.portal_check_available);
    const res = await api.refresh({ portal: usePortal });
    let st = await api.status();
    if (st.portal && st.portal.status === "running") st = await pollPortal();
    state.status = st;
    showStatus(st);
    await route();
    if (!quiet) {
      const portalMsg = st.portal && st.portal.checked_at && st.portal.status !== "unavailable" ? ` ${st.portal.message}` : "";
      toast(`${(res.refresh && res.refresh.message) || "Data refreshed."}${portalMsg}`);
    }
  } catch (e) {
    showStatus(null, false, e);
    toast(`Refresh failed: ${e.message} The page still shows the data loaded at ${fmt.time(state.status && state.status.loaded_at)}.`, 8000);
  } finally {
    state.refreshing = false;
    btn.disabled = false;
    btn.querySelector("svg").classList.remove("spin");
  }
}

// ---------------------------------------------------------------- theme & menu
function setTheme(t) {
  if (t === "auto") delete document.documentElement.dataset.theme; else document.documentElement.dataset.theme = t;
  try { if (t === "auto") localStorage.removeItem("eplanes-theme"); else localStorage.setItem("eplanes-theme", t); } catch (e) { /* storage blocked */ }
  document.querySelectorAll("[data-theme-set]").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.themeSet === (document.documentElement.dataset.theme || "auto"))));
}

function setupMenu() {
  const sb = document.getElementById("settings-btn"), menu = document.getElementById("settings-menu");
  sb.addEventListener("click", () => { const open = menu.hidden; menu.hidden = !open; sb.setAttribute("aria-expanded", String(open)); });
  document.addEventListener("click", (e) => { if (!menu.hidden && !e.target.closest("#settings-menu,#settings-btn")) { menu.hidden = true; sb.setAttribute("aria-expanded", "false"); } });
  document.querySelectorAll("[data-theme-set]").forEach((b) => b.addEventListener("click", () => setTheme(b.dataset.themeSet)));
  setTheme(document.documentElement.dataset.theme || "auto");
  const auto = document.getElementById("auto-refresh");
  try { auto.checked = localStorage.getItem("eplanes-auto") === "1"; } catch (e) { /* ignore */ }
  const arm = () => {
    clearInterval(state.autoTimer);
    if (auto.checked) state.autoTimer = setInterval(() => refresh({ quiet: true }), 10 * 60 * 1000);
  };
  auto.addEventListener("change", () => { try { localStorage.setItem("eplanes-auto", auto.checked ? "1" : "0"); } catch (e) { /* ignore */ } arm(); });
  arm();
}

function textAffiliations() {
  return h("div", { class: "text-aff" }, h("div", {}, "University of Waterloo"), h("div", {}, "Waterloo Institute for Sustainable Aeronautics"), h("div", {}, "Region of Waterloo International Airport"));
}

async function setupLogos() {
  const box = document.getElementById("logos");
  try {
    const site = await fetch("img/site.json", { cache: "no-store" }).then((r) => r.json());
    state.site = site;
    const light = getComputedStyle(document.documentElement).colorScheme === "light";
    let shown = 0;
    for (const l of site.logos || []) {
      const src = light && l.file_light ? l.file_light : l.file;
      const ok = await fetch(src, { method: "HEAD" }).then((r) => r.ok).catch(() => false);
      const okAlt = !ok && l.file_light ? await fetch(light ? l.file : l.file_light, { method: "HEAD" }).then((r) => r.ok).catch(() => false) : false;
      if (ok || okAlt) {
        box.append(h("a", { href: l.href, target: "_blank", rel: "noopener" }, h("img", { src: ok ? src : (light ? l.file : l.file_light), alt: l.name })));
        shown += 1;
      }
    }
    if (!shown) box.append(textAffiliations());
  } catch (e) {
    box.append(textAffiliations());
  }
}

async function boot() {
  setupMenu();
  btn.addEventListener("click", () => refresh());
  window.addEventListener("hashchange", route);
  onThemeChange(() => { route(); document.getElementById("logos").innerHTML = ""; setupLogos(); });
  try {
    state.status = await api.status();
    showStatus(state.status);
  } catch (e) {
    showStatus(null, false, e);
    app.innerHTML = "";
    app.append(h("div", { class: "wrap section" }, errorBox(e, () => location.reload())));
    setupLogos();
    return;
  }
  setupLogos();
  await route();
}

boot();
