"""Publish the website as a static snapshot to a git repository that Render (or any static host) deploys.

    python -m eplanes publish-site --site-repo git@github.com:<you>/eplanes-site.git [--refresh]

--refresh first runs the pipeline on this computer (download new sessions -> all -> export-web), so the portal
credentials never leave it. The snapshot is then built, scanned for the values in .env, copied into a local clone of
the site repository (outputs/site_repo), committed and pushed. Render redeploys on the push.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

from ..config import Settings

RENDER_YAML = """\
# Render Blueprint: a static site served from the prebuilt snapshot in this repository.
# Generated by `python -m eplanes publish-site`; edits are overwritten on the next publish.
services:
  - type: web
    name: eplanes
    runtime: static
    buildCommand: echo "prebuilt snapshot, nothing to build"
    staticPublishPath: .
    headers:
      - path: /data/*
        name: Cache-Control
        value: no-cache
      - path: /config.js
        name: Cache-Control
        value: no-cache
      - path: /*
        name: X-Content-Type-Options
        value: nosniff
"""

README = """\
# Eplanes website snapshot

Generated by `python -m eplanes publish-site` from the Eplanes pipeline; do not edit by hand.
The code that builds it is in the separate code repository. Render deploys this repository as a static site (render.yaml).

Last published: {when} ({n} sessions).
"""


def _run(cmd: list[str], cwd: Path | None = None, log=print, check: bool = True) -> subprocess.CompletedProcess:
    log("$ " + " ".join(cmd))
    return subprocess.run(cmd, cwd=cwd, check=check, text=True, capture_output=False)


def _env_values(root: Path) -> list[bytes]:
    p = root / ".env"
    if not p.exists():
        return []
    vals = [l.split("=", 1)[1].strip().strip("\"'") for l in p.read_text().splitlines()
            if "=" in l and not l.lstrip().startswith("#")]
    return [v.encode() for v in vals if len(v) >= 4]


def scan_for_secrets(site: Path, root: Path) -> list[str]:
    """Files in the snapshot that contain any value from .env (names only; values are never printed)."""
    vals = _env_values(root)
    if not vals:
        return []
    return [str(p.relative_to(site)) for p in site.rglob("*") if p.is_file() and any(v in p.read_bytes() for v in vals)]


def publish_site(settings: Settings, site_repo: str, refresh: bool = False, downloads_url: str | None = None,
                 release: Path | None = None, branch: str = "main", log=print) -> bool:
    from .server import build_static
    root = settings.root if hasattr(settings, "root") else Path.cwd()
    py = [sys.executable, "-m", "eplanes"]
    if refresh:
        _run(py + ["download"], log=log)          # resumable: only sessions not yet downloaded
        _run(py + ["all"], log=log)               # build, quality, analysis
        _run(py + ["export-web"], log=log)
    bundle = settings.outputs_dir / "web_bundle"
    if not (bundle / "manifest.json").exists():
        raise SystemExit(f"No web bundle at {bundle}: run `python -m eplanes export-web` first (or use --refresh).")

    build_dir = settings.outputs_dir / "web_static_publish"
    build_static(bundle, build_dir, release, downloads_url=downloads_url)
    hits = scan_for_secrets(build_dir, Path(root))
    if hits:
        raise SystemExit(f"STOP: values from .env appear in the snapshot ({', '.join(hits[:5])}). Nothing was published.")
    log("credential scan: no .env values in the snapshot")

    repo = settings.outputs_dir / "site_repo"
    if not (repo / ".git").exists():
        if repo.exists():
            shutil.rmtree(repo)
        _run(["git", "clone", site_repo, str(repo)], log=log)
    else:
        _run(["git", "fetch", "origin"], cwd=repo, log=log, check=False)
    _run(["git", "checkout", "-B", branch], cwd=repo, log=log)
    if subprocess.run(["git", "rev-parse", "--verify", f"origin/{branch}"], cwd=repo, capture_output=True).returncode == 0:
        _run(["git", "reset", "--hard", f"origin/{branch}"], cwd=repo, log=log)

    for p in repo.iterdir():
        if p.name != ".git":
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    shutil.copytree(build_dir, repo, dirs_exist_ok=True)
    n = sum(1 for _ in (build_dir / "data" / "sessions").glob("*.json"))
    when = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    (repo / "render.yaml").write_text(RENDER_YAML)
    (repo / "README.md").write_text(README.format(when=when, n=n))

    _run(["git", "add", "-A"], cwd=repo, log=log)
    if subprocess.run(["git", "diff", "--cached", "--quiet"], cwd=repo).returncode == 0:
        log("site unchanged: nothing to publish")
        return False
    _run(["git", "commit", "-q", "-m", f"Snapshot {when} ({n} sessions)"], cwd=repo, log=log)
    _run(["git", "push", "-u", "origin", f"{branch}:{branch}"], cwd=repo, log=log)
    log(f"published {n} sessions; Render redeploys from {site_repo} ({branch})")
    return True
